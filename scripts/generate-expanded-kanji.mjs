import { writeFile } from "node:fs/promises";

const levels = [2, 3, 4, 5];
const endpoint = "https://kanjiapi.dev/v1/kanji";

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
  return response.json();
}

async function mapLimit(items, limit, mapper) {
  const results = new Array(items.length);
  let index = 0;
  async function worker() {
    while (index < items.length) {
      const current = index;
      index += 1;
      results[current] = await mapper(items[current], current);
    }
  }
  await Promise.all(Array.from({ length: limit }, worker));
  return results;
}

const levelLists = await Promise.all(levels.map(async (level) => [level, await fetchJson(`${endpoint}/jlpt-${level}`)]));
const levelByKanji = new Map();
const ordered = [];
for (const [level, kanjiList] of levelLists) {
  for (const kanji of kanjiList) {
    if (!levelByKanji.has(kanji)) ordered.push(kanji);
    levelByKanji.set(kanji, Math.min(levelByKanji.get(kanji) ?? level, level));
  }
}

const details = await mapLimit(ordered, 12, async (kanji) => {
  const data = await fetchJson(`${endpoint}/${encodeURIComponent(kanji)}`);
  const readings = [...(data.on_readings ?? []), ...(data.kun_readings ?? [])];
  return {
    kanji: data.kanji,
    readings: readings.length ? readings : ["reading varies"],
    meanings: (data.meanings ?? ["common-use kanji"]).slice(0, 4),
    jlpt: levelByKanji.get(kanji),
    strokes: data.stroke_count ?? 0
  };
});

details.sort((a, b) => {
  if (a.jlpt !== b.jlpt) return a.jlpt - b.jlpt;
  return a.kanji.localeCompare(b.kanji, "ja");
});

const rows = details.map((item) => [
  item.kanji,
  item.readings.join("、"),
  item.meanings.join("; "),
  item.jlpt,
  item.strokes
].map((part) => String(part).replaceAll("|", " ")).join("|"));

const file = `import type { KanjiItem } from "../types";

// Generated by scripts/generate-expanded-kanji.mjs from kanjiapi.dev JLPT 2-5 buckets.
// This provides a broad cumulative N2-ish kanji flashcard bank for offline study.
const expandedKanjiRows = ${JSON.stringify(rows, null, 2)};

export const expandedKanji: KanjiItem[] = expandedKanjiRows.map((row, index) => {
  const [kanji, readings, meanings, jlpt, strokes] = row.split("|");
  const difficulty = jlpt === "2" ? 4 : jlpt === "3" ? 3 : 2;
  return {
    id: \`ek-\${String(index + 1).padStart(4, "0")}\`,
    kanji,
    readings: readings.split("、").filter(Boolean),
    meaning: meanings,
    exampleCompound: kanji,
    exampleSentence: \`「\${kanji}」はN2までの重要漢字として、読みと意味を文脈で確認する。\`,
    tags: [\`jlpt-\${jlpt}\`, \`strokes-\${strokes}\`, "expanded-kanji"],
    difficulty: difficulty as KanjiItem["difficulty"]
  };
});
`;

await writeFile("src/data/expandedKanji.ts", file, "utf8");
console.log(`Wrote ${details.length} expanded kanji to src/data/expandedKanji.ts`);
