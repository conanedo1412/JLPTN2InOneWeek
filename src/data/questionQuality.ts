function kanaCost(a: string, b: string): number {
  if (a === b) return 0;
  const groups = ["かが", "きぎ", "くぐ", "けげ", "こご", "さざ", "しじ", "すず", "せぜ", "そぞ", "ただ", "ちぢ", "つづっ", "てで", "とど", "はばぱ", "ひびぴ", "ふぶぷ", "へべぺ", "ほぼぽ", "やゃ", "ゆゅ", "よょ"];
  if (groups.some(group => group.includes(a) && group.includes(b))) return 0.25;
  const rows = ["あいうえお", "かきくけこがぎぐげご", "さしすせそざじずぜぞ", "たちつてとだぢづでど", "なにぬねの", "はひふへほばびぶべぼぱぴぷぺぽ", "まみむめも", "やゆよ", "らりるれろ", "わをん"];
  return rows.some(row => row.includes(a) && row.includes(b)) ? 0.5 : 1;
}

function distance(a: string, b: string): number {
  a = normalizeReading(a);
  b = normalizeReading(b);
  let previous = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const current = [i];
    for (let j = 1; j <= b.length; j++) current[j] = Math.min(current[j - 1] + 1, previous[j] + 1, previous[j - 1] + kanaCost(a[i - 1], b[j - 1]));
    previous = current;
  }
  return previous[b.length];
}
